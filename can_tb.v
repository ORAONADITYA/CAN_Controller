`timescale 1ns/1ps

module can_tb;
    reg clk;
    reg reset;
    reg tx_start;
    reg [10:0] identifier;
    reg [3:0] dlc;
    reg [63:0] data;

    wire tx_bit;
    wire tx_busy;
    wire tx_done;
    wire rx_done;
    wire [159:0] rx_frame;
    wire [7:0] rx_length;
    wire [7:0] frame_length;
    wire rx_active;

    reg [10:0] id_a;
    reg [10:0] id_b;
    wire winner_valid;
    wire winner;
    wire tie;

    integer vector_file;
    integer scan_result;
    integer temp_value;
    integer speed_value;
    integer voltage_value;
    integer sample_number;

    can_controller dut (
        .clk(clk),
        .reset(reset),
        .tx_start(tx_start),
        .identifier(identifier),
        .dlc(dlc),
        .data(data),
        .tx_bit(tx_bit),
        .tx_busy(tx_busy),
        .tx_done(tx_done),
        .rx_done(rx_done),
        .rx_frame(rx_frame),
        .rx_length(rx_length),
        .frame_length(frame_length),
        .rx_active(rx_active)
    );

    can_arbitration arbitration (
        .id_a(id_a),
        .id_b(id_b),
        .winner_valid(winner_valid),
        .winner(winner),
        .tie(tie)
    );

    always #5 clk = ~clk;

    task transmit_and_check;
        begin
            @(negedge clk);
            tx_start = 1'b1;
            @(negedge clk);
            tx_start = 1'b0;

            wait(tx_done);
            wait(rx_done);
            #1;

            if (rx_length == frame_length && rx_frame == dut.generated_frame)
                $display("PASS: TX/RX loopback matched. ID=%03h DLC=%0d frame_bits=%0d",
                         identifier, dlc, frame_length);
            else
                $display("FAIL: TX/RX loopback mismatch. ID=%03h", identifier);

            repeat (2) @(negedge clk);
        end
    endtask

    initial begin
        clk = 1'b0;
        reset = 1'b1;
        tx_start = 1'b0;
        identifier = 11'h123;
        dlc = 4'd3;
        data = 64'h1122334455667788;
        id_a = 11'h120;
        id_b = 11'h250;
        sample_number = 0;

        repeat (3) @(negedge clk);
        reset = 1'b0;

        // Basic frame test.
        transmit_and_check();

        // Arbitration test: lower numerical identifier wins.
        #1;
        if (winner_valid && !winner && !tie)
            $display("PASS: Arbitration - ID A (%03h) wins over ID B (%03h)", id_a, id_b);
        else
            $display("FAIL: Arbitration test");

        // Read the 16 sensor samples generated by Python.
        vector_file = $fopen("test_vectors.txt", "r");
        if (vector_file == 0) begin
            $display("NOTE: test_vectors.txt not found; basic test completed.");
        end else begin
            while (!$feof(vector_file)) begin
                scan_result = $fscanf(vector_file, "%d %d %d\n",
                                      temp_value, speed_value, voltage_value);
                if (scan_result == 3) begin
                    // Example mapping into an 8-byte CAN payload:
                    // temperature x10 (16 bits), speed (16 bits),
                    // voltage x10 (16 bits), sample counter (16 bits).
                    data = {temp_value[15:0], speed_value[15:0],
                            voltage_value[15:0], sample_number[15:0]};
                    identifier = 11'h120;
                    dlc = 4'd8;
                    transmit_and_check();
                    sample_number = sample_number + 1;
                end
            end
            $fclose(vector_file);
        end

        $display("Simulation finished.");
        $finish;
    end
endmodule
